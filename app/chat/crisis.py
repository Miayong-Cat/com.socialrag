"""위기 신호 감지 — 사용자 말에 자살·학대·긴급 생계 위기 신호가 있는지 규칙으로 찾는다.

왜 LLM 이 아니라 규칙(키워드)인가:
    생명·안전에 관한 판단이라 API 장애·거절·모델 판단 차이에 흔들리면 안 된다.
    같은 말에는 항상 같게 반응하고, 놓치지 않는 쪽(넓게 잡기)을 택했다.
    대신 일반 질문을 막지 않도록 위기 종류마다 대응을 다르게 한다:

| 종류        | 대응 (level)                                  | 이유                                         |
|-------------|-----------------------------------------------|----------------------------------------------|
| suicide     | stop   — 일반 흐름을 멈추고 상담 전화 안내만   | 지금 당장의 안전이 먼저                       |
|             | notice — 제도 질문 속 낱말일 때만 (detect 참고) | "자살예방 지원 제도"를 물으면 답도 해야 함    |
| abuse       | notice — 안내를 맨 앞에 붙이고 답변은 계속     | "가정폭력 피해자 특례" 같은 제도 질문도 많음  |
| livelihood  | notice — 긴급복지지원 안내 + 답변 계속         | 수급 판정·신청 안내가 바로 도움이 됨          |

안내 전화번호 (2026년 기준 — 바뀔 수 있으니 주기적으로 확인할 것):
    109 자살예방 상담전화(24시간), 1577-0199 정신건강 위기상담, 119 응급, 112 범죄·아동학대 신고,
    1366 여성긴급전화(가정폭력·성폭력), 1577-1389 노인학대 신고, 1644-8295 장애인학대 신고,
    129 보건복지상담센터(긴급복지지원 — 지침서 p.2)
"""

import re
from dataclasses import dataclass


@dataclass
class Crisis:
    """감지된 위기 신호."""

    category: str   # "suicide" / "abuse" / "livelihood"
    level: str      # "stop" = 일반 흐름 중단 / "notice" = 안내를 붙이고 계속
    message: str    # 사용자에게 보여 줄 안내


# (종류, 대응, 신호 정규식, 안내) — 위에서부터 먼저 맞는 것 하나만 쓴다 (가장 급한 것이 위)
RULES = [
    (
        "suicide",
        "stop",
        re.compile(
            r"죽고\s*싶|자살|극단적\s*선택|목숨을\s*끊|살기\s*싫|살고\s*싶지\s*않|사라지고\s*싶|"
            r"다\s*끝내고\s*싶|세상을\s*떠나고\s*싶|자해|손목을\s*긋|유서"
        ),
        "많이 힘드신 것 같아요. 지금 이야기해 주셔서 고맙습니다.\n"
        "혼자 견디지 않으셔도 됩니다. 지금 바로 전문 상담사와 이야기할 수 있어요.\n\n"
        "- **자살예방 상담전화 109** (24시간, 무료)\n"
        "- **정신건강 위기상담 1577-0199** (24시간)\n"
        "- 지금 위험한 상황이라면 **119** 또는 **112**\n\n"
        "마음이 조금 진정되면, 생활비나 급여 문제도 여기서 같이 알아봐 드릴게요.",
    ),
    (
        "abuse",
        "notice",
        re.compile(r"학대|때려요|때린다|때려서|맞고\s*있|맞았어|폭행|폭력|위협(을|당)|감금|협박"),
        "⚠️ 폭력이나 학대를 겪고 계신다면 먼저 도움을 받으세요.\n"
        "- 지금 위험하면 **112** (아동학대도 112)\n"
        "- 가정폭력·성폭력 **1366** (여성긴급전화, 24시간) · 노인학대 **1577-1389** · 장애인학대 **1644-8295**",
    ),
    (
        "livelihood",
        "notice",
        re.compile(
            r"굶|끼니|먹을\s*(게|것|거|쌀|밥)\S{0,2}\s*없|쌀(이|도)?\s*(떨어|없)|단전|단수|전기가?\s*끊|가스가?\s*끊|"
            r"쫓겨나|내쫓|퇴거|길에서\s*자|노숙|잘\s*곳이\s*없|당장\s*(돈|생활비)"
        ),
        "⚠️ 당장 생계가 어려우시면 **긴급복지지원**을 먼저 알아보세요. 심사 전에 생계비·주거비 등을 먼저 지원받을 수 있어요.\n"
        "- **보건복지상담센터 129** 또는 주소지 읍·면·동 행정복지센터",
    ),
]


# 자살 신호 중 "본인의 지금 마음"이 드러나는 말 — 정보 질문 문맥이 함께 있어도 항상 stop
SUICIDE_FIRST_PERSON = re.compile(
    r"죽고\s*싶|자살\s*(하고\s*싶|할\s*(까|거|래)|생각)|목숨을\s*끊|살기\s*싫|살고\s*싶지\s*않|사라지고\s*싶|"
    r"다\s*끝내고\s*싶|세상을\s*떠나고\s*싶|손목을\s*긋|유서|자해\s*(하고\s*싶|했|하고\s*있)"
)
# 제도·사업을 묻는 정보 질문 문맥 — "자살예방 상담 지원 제도가 있나요?", "자살 유가족 지원 사업"
INFO_CONTEXT = re.compile(r"예방|지원|제도|사업|센터|기관|정책|유가족|프로그램|상담\s*(전화|번호|센터)|급여|혜택|신청")
SUICIDE_INFO_NOTICE = (
    "※ 혹시 지금 힘든 마음이 드신다면 **자살예방 상담전화 109**(24시간, 무료)에서 바로 이야기할 수 있어요. "
    "정신건강 위기상담 **1577-0199**도 24시간 열려 있어요."
)


def detect(text: str) -> Crisis | None:
    """말 한 마디 → 위기 신호 (없으면 None).

    자살 신호의 예외: "자살·자해" 같은 낱말이 제도·사업을 묻는 정보 질문 안에만 있고 본인의 지금 마음(SUICIDE_FIRST_PERSON)이
    드러나지 않으면 stop 대신 notice — 109 안내를 앞에 붙이고 질문에도 답한다.
    (전에는 "자살예방 상담 지원 제도가 있나요?"도 흐름을 멈춰 질문에 답하지 못했다 — 4차 독립 리뷰)
    놓치지 않는 쪽은 그대로다: 종류(category)는 여전히 suicide 이고, 안내도 항상 보여 준다.
    """
    for category, level, pattern, message in RULES:
        if pattern.search(text):
            if category == "suicide" and not SUICIDE_FIRST_PERSON.search(text) and INFO_CONTEXT.search(text):
                return Crisis(category=category, level="notice", message=SUICIDE_INFO_NOTICE)
            return Crisis(category=category, level=level, message=message)
    return None
